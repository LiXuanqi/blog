import { readFile, mkdir, writeFile, rename } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, join } from "node:path";
import { yamlProvider } from "@resume-sdk/core/providers";
import {
  renderFragment,
  renderDocument,
  getTemplate,
} from "@resume-sdk/core/renderer";
import { exportPdf } from "@resume-sdk/cli/pdf";
import config from "../../resume.config.mjs";

const root = fileURLToPath(new URL("../../", import.meta.url));
const generated = join(root, "src/generated/resume");
const pdfPath = join(root, "public/resume.pdf");

async function generate() {
  const { resume } = await yamlProvider.load(
    await readFile(resolve(root, config.source), "utf8"),
  );
  const template = getTemplate(config.template);
  const fragment = renderFragment(resume, config.options, template);
  const pdf = await exportPdf(renderDocument(resume, config.options, template));

  // Finish conversion and rendering before replacing any working artifacts.
  await mkdir(generated, { recursive: true });
  await mkdir(join(root, "public"), { recursive: true });
  const artifacts = [
    [join(generated, "resume.html"), fragment.html],
    [join(generated, "resume.css"), fragment.css],
    // A static import lets Next bundle the HTML without runtime filesystem access.
    [
      join(generated, "resume.ts"),
      `// Generated by pnpm generate:resume. Do not edit.\nexport const html = ${JSON.stringify(fragment.html)};\n`,
    ],
    [pdfPath, pdf],
  ];
  for (const [path, content] of artifacts) {
    const temporary = `${path}.${process.pid}.tmp`;
    await writeFile(temporary, content);
    await rename(temporary, path);
  }
  console.log("Generated resume HTML, scoped CSS, and public/resume.pdf.");
}

generate().catch((error) => {
  console.error("Resume generation failed:", error.message);
  process.exitCode = 1;
});
